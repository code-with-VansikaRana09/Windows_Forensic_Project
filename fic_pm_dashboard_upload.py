import io
import pandas as pd
import streamlit as st
from fic_pm_upload_engine import run_analysis

st.set_page_config(page_title="FIC-PM | Upload Analysis", layout="wide")
st.title("FIC-PM")
st.subheader("Forensic Investigation & Corroboration — Priority Management")
st.caption("Upload evidence collected by FIC-PM on a Windows endpoint. Analysis is performed on the uploaded dataset.")

st.info("This dashboard does not scan the visitor's computer. Run the FIC-PM collector locally first, then upload its four CSV outputs.")
st.warning("Use only with the device owner's permission. Uploaded evidence may contain software names, device identifiers, paths and other sensitive system information. Avoid uploading data you are not authorized to share.")

def load_csv(upload, label):
    if upload is None:
        return None
    try:
        return pd.read_csv(upload)
    except Exception as exc:
        st.error(f"Could not read {label} CSV: {exc}")
        return None

with st.sidebar:
    st.header("Endpoint evidence upload")
    st.caption("Choose the four CSV files from the collector's Data folder.")
    software_file = st.file_uploader("1. live_software.csv", type=["csv"], key="sw")
    usb_file = st.file_uploader("2. live_usb.csv", type=["csv"], key="usb")
    startup_file = st.file_uploader("3. live_startup.csv", type=["csv"], key="startup")
    prefetch_file = st.file_uploader("4. live_prefetch_inventory.csv", type=["csv"], key="pf")
    run = st.button("Analyze uploaded endpoint", type="primary", use_container_width=True,
                    disabled=not all([software_file, usb_file, startup_file, prefetch_file]))

st.markdown("### Upload requirements")
st.write("Upload the original CSVs generated by `fic_pm_live_collector.py`. Do not upload the old `Reports/FIC_PM_LIVE_PRIORITY.csv`; the online dashboard recalculates the features, detectors, correlations and scores.")

if run:
    try:
        software = load_csv(software_file, "Software")
        usb = load_csv(usb_file, "USB")
        startup = load_csv(startup_file, "Startup")
        prefetch = load_csv(prefetch_file, "Prefetch")
        if any(x is None for x in [software, usb, startup, prefetch]):
            st.stop()
        with st.spinner("Running feature engineering, anomaly detectors, evidence correlation and priority scoring..."):
            priority, detectors, startup, usb, prefetch = run_analysis(software, usb, startup, prefetch)
        st.session_state["ficpm_result"] = {
            "priority": priority, "detectors": detectors,
            "startup": startup, "usb": usb, "prefetch": prefetch,
            "software_count": len(software)
        }
        st.session_state["ficpm_upload_names"] = [
            software_file.name, usb_file.name, startup_file.name, prefetch_file.name
        ]
    except Exception as exc:
        st.error(f"Analysis could not be completed: {exc}")
        st.stop()

result = st.session_state.get("ficpm_result")
if result is None:
    st.markdown("### How to use")
    st.markdown("""
    1. On the Windows laptop, extract the FIC-PM project.
    2. Run `RUN_FIC_PM.bat` to collect evidence and create the CSV files.
    3. Upload the four CSV files listed in the sidebar.
    4. Select **Analyze uploaded endpoint**.
    5. Review and download the priority queue.
    """)
    st.stop()

df = result["priority"]
detectors = result["detectors"]
startup = result["startup"]
usb = result["usb"]
pf = result["prefetch"]

st.success("Analysis completed for the currently uploaded endpoint dataset.")
st.caption("Uploaded files: " + " · ".join(st.session_state.get("ficpm_upload_names", [])))

c1,c2,c3,c4,c5 = st.columns(5)
c1.metric("Software artifacts", len(df))
c2.metric("Detector flagged", int((df["Anomaly_Detector_Count"] > 0).sum()))
c3.metric("Startup matches", int((df["Startup_Match_Count"] > 0).sum()))
c4.metric("Prefetch linked", int((df["Prefetch_Match_Count"] > 0).sum()))
c5.metric("USB records", len(usb))

tab1,tab2,tab3,tab4,tab5 = st.tabs([
    "Overview", "Prioritized Investigation", "Detector Analysis",
    "Startup & USB", "Prefetch Evidence"
])
with tab1:
    st.subheader("Priority distribution")
    st.bar_chart(df["Priority_Level"].value_counts())
    st.subheader("Detector agreement")
    st.bar_chart(df["Anomaly_Detector_Count"].value_counts().sort_index())
    st.info("Scores are experimental investigation-priority heuristics, not malware probabilities or verdicts.")

with tab2:
    st.subheader("Ranked investigation queue")
    levels = sorted(df["Priority_Level"].astype(str).unique())
    selected = st.multiselect("Priority levels", levels, default=levels)
    query = st.text_input("Search software")
    view = df[df["Priority_Level"].astype(str).isin(selected)].copy()
    if query:
        view = view[view["Software_Name"].astype(str).str.contains(query, case=False, na=False)]
    cols = ["Priority_Rank","Software_Name","FIC_PM_Score","Priority_Level",
            "Anomaly_Detector_Count","Startup_Match_Count","Prefetch_Match_Count",
            "Metadata_Gap_Count","Review_Reason"]
    st.dataframe(view[cols], use_container_width=True, hide_index=True)
    st.download_button("Download priority queue CSV", view.to_csv(index=False).encode("utf-8-sig"),
                       "FIC_PM_uploaded_priority.csv", "text/csv")
    if not view.empty:
        selected_name = st.selectbox("Inspect artifact", view["Software_Name"].tolist())
        row = view[view["Software_Name"] == selected_name].iloc[0]
        st.write(f"**Score:** {row['FIC_PM_Score']} / 100  ·  **Priority:** {row['Priority_Level']}")
        breakdown = pd.DataFrame({"Component":["Detector consensus","Startup association","Prefetch linkage"],
                                  "Points":[row["Detector_Component"],row["Startup_Component"],row["Prefetch_Component"]],
                                  "Maximum":[60,20,20]})
        st.dataframe(breakdown, use_container_width=True, hide_index=True)
        st.write("**Review reasons:**", row["Review_Reason"])
        st.write("**Matched startup executables:**", row["Startup_Matched_Executables"])
        st.write("**Matched Prefetch files:**", row["Prefetch_Matched_Files"])
        st.write("**Registry path:**", row["Registry_Path"])
        st.write("**Install location:**", row["Install_Location"])

with tab3:
    st.subheader("Detector results")
    detector_summary = pd.DataFrame({
        "Detector":["Isolation Forest","LOF","One-Class SVM"],
        "Flagged":[int(detectors["IF_Flag"].sum()),int(detectors["LOF_Flag"].sum()),int(detectors["SVM_Flag"].sum())]
    })
    st.bar_chart(detector_summary.set_index("Detector"))
    st.dataframe(detectors.sort_values("Anomaly_Detector_Count",ascending=False),
                 use_container_width=True,hide_index=True)
    st.download_button("Download detector output",detectors.to_csv(index=False).encode("utf-8-sig"),
                       "FIC_PM_uploaded_detectors.csv","text/csv")

with tab4:
    st.subheader("Startup entries")
    st.dataframe(startup,use_container_width=True,hide_index=True)
    st.subheader("USB storage records")
    st.dataframe(usb,use_container_width=True,hide_index=True)

with tab5:
    st.caption("Prefetch file inventory only; this is not a parsed execution timeline.")
    st.dataframe(pf,use_container_width=True,hide_index=True)
    st.download_button("Download Prefetch inventory",pf.to_csv(index=False).encode("utf-8-sig"),
                       "FIC_PM_uploaded_prefetch.csv","text/csv")

st.divider()
st.caption("FIC-PM experimental prototype. Name-based matches are heuristic. Detector flags and scores require independent forensic corroboration.")
